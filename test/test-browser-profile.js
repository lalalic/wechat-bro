'use strict'
const assert = require('assert')
const fs = require('fs')
const path = require('path')
const pkg = require('../package.json')
const cli = fs.readFileSync(path.join(__dirname,'../src/cli.js'),'utf8')
const cdp = fs.readFileSync(path.join(__dirname,'../src/cdp.js'),'utf8')
assert(!pkg.dependencies.puppeteer, 'no Puppeteer dependency')
assert(!pkg.scripts.postinstall, 'no downloaded Chrome')
assert(cdp.includes("name: WECHAT_WORKSPACE"), 'app provisions a dedicated WeChat group')
assert(cdp.includes("op: 'heartbeat'"), 'long-lived session heartbeat')
assert(cdp.includes("op: 'workspace-delete'"), 'exit destroys the WeChat Group')
assert(cdp.includes("op: 'stop'"), 'Session record cleanup after group tab destruction')
assert(cdp.includes("current.target_id"), 'wait for CDP target destruction before Session stop')
assert(!cli.includes('puppeteer.launch'), 'no standalone Chrome launcher')
console.log('browser profile: WebHelm owns all browser lifecycle and cookies')
